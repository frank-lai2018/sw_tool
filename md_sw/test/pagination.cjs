const { _electron } = require('playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');

(async () => {
  const root = path.resolve(__dirname, '..');
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'md-pages-'));
  const development = process.argv.includes('--dev');
  const file = path.join(temp, 'large.md');
  const rows = Array.from({ length: 6000 }, (_, n) => `| row-${n} | [連結](https://example.com/${n}) | 很長的中文測試資料 ${'abc '.repeat(12)} | ${n === 100 || n === 5900 ? 'CROSS-PAGE-NEEDLE' : '一般資料'} |`);
  await fs.writeFile(file, '# 首頁\n\n[末頁連結](#末頁)\n\n| 編號 | 網頁 | 說明 | 標記 |\n|---|---|---|---|\n' + rows.join('\n') + '\n\n## 末頁\n\nLAST-UNIQUE-NEEDLE\n<script>window.injected=true</script>\n');
  const app = await _electron.launch({ executablePath: development ? require('electron') : path.join(root, 'dist/win-unpacked/MD Reader.exe'), args: [...(development ? [root] : []), `--user-data-dir=${path.join(temp, 'profile')}`, file] });
  const errors = [];
  try {
    const page = await app.firstWindow(); page.setDefaultTimeout(20000); page.on('pageerror', e => errors.push(e.message));
    await page.waitForFunction(() => document.querySelector('#document-state').textContent === '分頁閱讀' && document.querySelector('#content h1')?.textContent === '首頁');
    const total = Number(await page.locator('#page-number').getAttribute('max')); assert.ok(total > 10);
    assert.equal(await page.locator('#source').textContent(), '');
    assert.equal(await page.locator('#toc a').count(), 2);
    await page.locator('#toc a').last().click();
    await page.waitForSelector('#md-heading-末頁');
    assert.match(await page.locator('#content').innerText(), /LAST-UNIQUE-NEEDLE/);
    assert.ok(Number(await page.locator('#page-number').inputValue()) > 1);
    assert.equal(await page.evaluate(() => window.injected), undefined);
    await page.locator('#toc a').first().click();
    await page.waitForSelector('#md-heading-首頁');
    await page.locator('#content a').filter({ hasText: '末頁連結' }).click();
    await page.waitForSelector('#md-heading-末頁');
    await page.click('#search-button'); await page.fill('#search-input', 'CROSS-PAGE-NEEDLE');
    await page.waitForFunction(() => document.querySelector('#search-result').textContent === '1 / 2');
    const firstPage = await page.locator('#page-number').inputValue();
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.querySelector('#search-result').textContent === '2 / 2');
    assert.notEqual(await page.locator('#page-number').inputValue(), firstPage);
    await page.keyboard.press('Shift+Enter');
    await page.waitForFunction(() => document.querySelector('#search-result').textContent === '1 / 2');
    assert.equal(await page.locator('#page-number').inputValue(), firstPage);
    await page.fill('#search-input', 'LAST-UNIQUE-NEEDLE');
    await page.waitForFunction(() => document.querySelector('#search-result').textContent === '1 / 1');
    assert.match(await page.locator('#content').innerText(), /LAST-UNIQUE-NEEDLE/);
    await page.keyboard.press('Escape');
    await page.click('#source-button');
    assert.ok((await page.locator('#source').textContent()).length < 64000);
    assert.equal(await page.locator('#content *').count(), 0);
    await page.click('#search-button'); await page.fill('#search-input', 'LAST-UNIQUE-NEEDLE');
    await page.waitForFunction(() => document.querySelector('#search-result').textContent === '1 / 1');
    assert.match(await page.locator('#source').textContent(), /LAST-UNIQUE-NEEDLE/);
    await page.keyboard.press('Escape');
    await page.click('#source-button');
    assert.equal(await page.locator('#source').textContent(), '');
    await app.evaluate(({ dialog }) => { dialog.showMessageBox = async (_, options) => { globalThis.printPrompt = options; return { response: 1 }; }; });
    await page.click('#print-button');
    const prompt = await app.evaluate(() => globalThis.printPrompt);
    assert.match(prompt.message, /共 .* 頁/); assert.equal(prompt.buttons[0], '列印目前頁');
    await page.locator('#page-number').fill('2'); await page.locator('#page-number').press('Enter');
    await page.waitForFunction(() => parseInt(document.querySelector('#progress').textContent) < 10);
    await page.screenshot({ path: path.join(root, 'test-output/pagination.png') });
    const small = path.join(temp, 'small.md'); await fs.writeFile(small, '# 小文件\n\n正常內容');
    // A pending worker must be cancelled when another document is opened.
    await page.evaluate(file => window.reader.openFile(file), file);
    await page.evaluate(file => window.reader.openFile(file), small);
    await page.waitForFunction(() => document.querySelector('#content h1')?.textContent === '小文件');
    assert.equal(await page.locator('#pagination').isHidden(), true);
    assert.deepEqual(errors, []);
    console.log('PASS: large tables, complete TOC, heading links, global search and forward/backward wrap across pages, bounded source view, print scope, sanitizing, and cancellation on file switch.');
  } finally { await app.close(); await fs.rm(temp, { recursive: true, force: true }); }
})().catch(e => { console.error(e); process.exitCode = 1; });
